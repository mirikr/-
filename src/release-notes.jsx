// Патч-ноут: окно по центру с размытым фоном. Раньше история пряталась в
// подвале «Синхронизации» — туда за ней никто не заходил, поэтому теперь её
// открывает номер версии, который виден всегда.
// Сравнение версий: ползунок ходит по истории, а рядом видно, как было до
// обновления и как стало после. Список «что нового» отвечает на вопрос «что
// добавили», а это — на вопрос «чем теперь иначе», и на больших обновлениях
// второй вопрос интереснее.
// Шторка «было / стало»: слева кусок старой версии, справа новой, между ними
// ручка. Так сравнивают карты в обзорах игр — и здесь это честнее любого
// описания: видно саму разницу, а не рассказ о ней.
function Wipe({ before, after, beforeLabel, afterLabel }) {
  const [pos, setPos] = useState(50);
  // Снимки весят по сотне килобайт и в офлайн-кэш не кладутся: на медленной
  // связи окно несколько секунд стояло пустым, будто сломалось.
  const [ready, setReady] = useState(false);
  const boxRef = useRef(null);
  const dragging = useRef(false);

  function setFromEvent(e) {
    const box = boxRef.current;
    if (!box) return;
    const rect = box.getBoundingClientRect();
    const x = ((e.clientX - rect.left) / rect.width) * 100;
    setPos(Math.max(0, Math.min(100, x)));
  }

  return (
    <div
      ref={boxRef}
      style={styles.wipe}
      onPointerDown={(e) => {
        dragging.current = true;
        e.currentTarget.setPointerCapture(e.pointerId);
        setFromEvent(e);
      }}
      onPointerMove={(e) => dragging.current && setFromEvent(e)}
      onPointerUp={() => (dragging.current = false)}
      onPointerCancel={() => (dragging.current = false)}
    >
      {!ready && (
        <div style={styles.wipeLoading}>
          {beforeLabel} → {afterLabel}
          <span style={styles.wipeLoadingNote}>снимки загружаются…</span>
        </div>
      )}
      <img
        src={after}
        alt={afterLabel}
        style={styles.wipeImg}
        draggable="false"
        onLoad={() => setReady(true)}
        onError={() => setReady(true)}
      />
      {/* Старая версия лежит сверху и обрезается ручкой — двигая её влево,
          вы «стираете» прошлое и видите нынешнее. */}
      <div style={{ ...styles.wipeClip, clipPath: `inset(0 ${100 - pos}% 0 0)` }}>
        <img src={before} alt={beforeLabel} style={styles.wipeImg} draggable="false" />
      </div>

      <div style={{ ...styles.wipeLine, left: pos + "%" }}>
        <div
          style={styles.wipeGrip}
          tabIndex={0}
          role="slider"
          aria-label="Сравнение версий"
          aria-valuenow={Math.round(pos)}
          aria-valuemin={0}
          aria-valuemax={100}
          onKeyDown={(e) => {
            if (e.key === "ArrowLeft") setPos((p) => Math.max(0, p - 4));
            if (e.key === "ArrowRight") setPos((p) => Math.min(100, p + 4));
          }}
        >
          ‹ ›
        </div>
      </div>

      <div style={{ ...styles.wipeTag, left: 8, opacity: pos > 12 ? 1 : 0 }}>{beforeLabel}</div>
      <div style={{ ...styles.wipeTag, right: 8, opacity: pos < 88 ? 1 : 0 }}>{afterLabel}</div>
    </div>
  );
}

function Compare({ onBack }) {
  const ordered = [...RELEASES].reverse();
  // «от» может быть и «до приложения» — это индекс -1, шаг перед первой версией.
  // Открываем на переходе, у которого есть снимки: сравнение словами доступно
  // всегда, а картинками — только здесь, и показать его стоит сразу.
  const lastPair = SHOT_PAIRS[SHOT_PAIRS.length - 1];
  const shotFrom = ordered.findIndex((r) => r.v === lastPair[0]);
  const shotTo = ordered.findIndex((r) => r.v === lastPair[1]);
  const [from, setFrom] = useState(shotFrom >= 0 && shotTo > shotFrom ? shotFrom : ordered.length - 2);
  const [to, setTo] = useState(shotFrom >= 0 && shotTo > shotFrom ? shotTo : ordered.length - 1);

  // Порядок концов не даём перепутать: выбрали «от» позже «до» — сдвигается
  // второй конец, а не появляется пустое сравнение задом наперёд.
  function pickFrom(next) {
    setFrom(next);
    if (next >= to) setTo(Math.min(ordered.length - 1, next + 1));
  }
  function pickTo(next) {
    setTo(next);
    if (next <= from) setFrom(next - 1);
  }

  const left = from >= 0 ? ordered[from] : null;
  const right = ordered[to];
  const steps = ordered.slice(from + 1, to + 1);
  const pairs = steps.flatMap((r) => r.changes || []);
  // Снимки есть у обоих концов — показываем картинки, даже если это концы
  // разных пар (0.7.0 → 1.0.0 тоже честное сравнение двух снимков).
  const shotSet = new Set(SHOT_PAIRS.flat());
  const hasShots = left && shotSet.has(left.v) && shotSet.has(right.v);

  return (
    <>
      <div style={styles.compareHead}>
        <button onClick={onBack} className="ap-version" style={styles.backBtn}>
          ← вся история
        </button>
        <div style={styles.compareVersions}>{left ? `${left.v} → ${right.v}` : `до приложения → ${right.v}`}</div>
      </div>

      {/* Версий уже полтора десятка, и подписями под ползунком они сливались в
          кашу из цифр. Два списка занимают столько же места независимо от того,
          сколько версий вышло, и позволяют сравнить любые две, а не соседние. */}
      <div style={styles.pickRow}>
        <label style={styles.pickCell}>
          <span style={styles.pickLabel}>от версии</span>
          <select value={from} onChange={(e) => pickFrom(Number(e.target.value))} style={styles.pickSelect}>
            <option value={-1}>до приложения</option>
            {ordered.slice(0, ordered.length - 1).map((r, i) => (
              <option key={r.v} value={i}>
                {r.v}
              </option>
            ))}
          </select>
        </label>
        <span style={styles.pickArrow} aria-hidden="true">
          →
        </span>
        <label style={styles.pickCell}>
          <span style={styles.pickLabel}>до версии</span>
          <select value={to} onChange={(e) => pickTo(Number(e.target.value))} style={styles.pickSelect}>
            {ordered.map((r, i) =>
              i === 0 ? null : (
                <option key={r.v} value={i}>
                  {r.v}
                </option>
              )
            )}
          </select>
        </label>
      </div>
      {steps.length > 1 && (
        <div style={styles.pickNote}>
          {steps.length} версий за этот промежуток, изменения собраны вместе.
        </div>
      )}

      {/* Картинки сняты из истории репозитория скриптом scripts/make-version-shots.mjs. */}
      {hasShots ? (
        <Wipe before={shotUrl(left.v)} after={shotUrl(right.v)} beforeLabel={left.v} afterLabel={right.v} />
      ) : (
        <div style={styles.noShots}>
          Снимками показаны переходы {SHOT_PAIRS.map((p) => p[0] + " → " + p[1]).join(" и ")}: там разница видна с
          первого взгляда. Этот шаг — словами.
        </div>
      )}

      <div style={styles.compareBody}>
        {pairs.map((pair, i) => (
          <div key={i} style={styles.pair}>
            <div style={styles.before}>
              <div style={styles.pairLabel}>было</div>
              {pair[0]}
            </div>
            <div style={styles.arrow} aria-hidden="true">
              →
            </div>
            <div style={styles.after}>
              <div style={styles.pairLabel}>стало</div>
              {pair[1]}
            </div>
          </div>
        ))}
        {!pairs.length && <div style={styles.list}>Для этого промежутка сравнение не записано.</div>}
      </div>
    </>
  );
}

