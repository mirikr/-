const MONTHS_IN = { 8: "Сентябрь", 9: "Октябрь" };

// Список на двадцать семь строк без разбивки читается как стена, поэтому он
// делится по месяцам — так же, как его и объявляют.
export function voshMonths() {
  const out = [];
  for (const item of VOSH) {
    const month = new Date(item.date + "T00:00:00").getMonth();
    let group = out.find((g) => g.month === month);
    if (!group) {
      group = { month, title: MONTHS_IN[month] || "Позже", items: [] };
      out.push(group);
    }
    group.items.push(item);
  }
  return out;
}

const DOW = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"];
const DAY_MONTH = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"];

export function humanDate(iso) {
  const d = new Date(iso + "T00:00:00");
  return d.getDate() + " " + DAY_MONTH[d.getMonth()];
}

export function buildOlympiads(picked) {
  const chosen = new Set(picked || []);
  return VOSH.filter((o) => chosen.has(o.id)).map((o) => ({
    id: "sch-" + VOSH_PRESET_ID + "-" + o.id,
    day: DOW[new Date(o.date + "T00:00:00").getDay()],
    kind: "exam",
    examKind: "olympiad",
    subjectName: o.name + " · ВсОШ",
    level: "base",
    priority: 3,
    start: VOSH_START,
    end: VOSH_END,
    room: "",
    teacher: "",
    place: [o.place, o.results ? "итоги " + humanDate(o.results) : ""].filter(Boolean).join(" · "),
    url: "",
    date: o.date,
    preset: VOSH_PRESET_ID,
  }));
}

