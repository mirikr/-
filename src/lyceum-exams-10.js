// Дата решает, в какой день недели встанет запись: экзамен в расписании живёт
// по дате, а не по клетке сетки.
const DOW = ["sun", "mon", "tue", "wed", "thu", "fri", "sat"];

export function buildExams(picked) {
  const chosen = new Set(picked || []);
  return KT_EXAMS.filter((e) => chosen.has(e.id)).map((e) => ({
    id: "sch-" + KT_PRESET_ID + "-" + e.id,
    day: DOW[new Date(e.date + "T00:00:00").getDay()],
    kind: "exam",
    examKind: "exam",
    subjectName: e.name,
    level: "base",
    priority: 3,
    start: e.start,
    end: e.end,
    room: "",
    teacher: "",
    place: [e.place, e.note].filter(Boolean).join(" · "),
    url: "",
    date: e.date,
    preset: KT_PRESET_ID,
  }));
}

export const DEFAULT_KT = KT_EXAMS.filter((e) => e.on).map((e) => e.id);
