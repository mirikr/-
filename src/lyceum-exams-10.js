// График контрольных тестов КТ1 для 3 курса (10 класс), сентябрь 2026.
//
// В методичке он общий на 8–11 классы: часть строк адресована другим курсам,
// часть — «учебным группам по данному предмету», то есть тем, кто предмет
// сдаёт. Поэтому здесь оставлено то, что касается 3 курса, а предметы
// отмечаются галочками.
//
// Время окончания в графике не указано — стоит ориентировочное, его видно в
// карточке и можно поправить.

export const KT_PRESET_ID = "kt1";

const at = (date, start, hours) => {
  const [h, m] = start.split(":").map(Number);
  const end = new Date(2000, 0, 1, h, m + Math.round(hours * 60));
  return { date, start, end: String(end.getHours()).padStart(2, "0") + ":" + String(end.getMinutes()).padStart(2, "0") };
};

// group — чтобы не спрашивать про каждую строку по отдельности:
//   subject — предмет, который сдают только его учебные группы;
//   common  — то, что касается всего курса;
//   extra   — то, на что идут по особому случаю (освобождение, пропуск).
const E = (id, group, name, date, start, hours, place, note, on) => ({
  id,
  group,
  name,
  ...at(date, start, hours),
  place,
  note: note || "",
  // Отмечено заранее: общее для курса берут все, остальное — по себе.
  on: on !== undefined ? on : group === "common",
});

