import React from "react";

// Путь к подписке у каждой системы свой, и различия не косметические:
// iPhone подписывается по ссылке одним касанием, Android из приложения
// Google Календаря — не умеет вовсе, там подписка заводится в веб-версии.
// Поэтому инструкция одна, но текст разный.
export default function CalendarHowTo({ platform, styles }) {
  if (platform === "ios") {
    return (
      <ol style={styles.calendarSteps}>
        <li>Нажмите «Подписаться» — iPhone спросит, в какой аккаунт добавить календарь.</li>
        <li>
          Готово: календарь «Ежедневник лицеиста» встанет рядом с остальными и будет обновляться сам, примерно раз в
          час.
        </li>
      </ol>
    );
  }

  if (platform === "android") {
    return (
      <>
        <ol style={styles.calendarSteps}>
          <li>Нажмите «Скопировать ссылку».</li>
          <li>
            Откройте <b>calendar.google.com</b> — с компьютера или в браузере телефона.
          </li>
          <li>Слева «Другие календари» → «+» → «Подписаться на календарь» → вставьте ссылку.</li>
          <li>Календарь появится и в приложении Google Календаря на телефоне.</li>
        </ol>
        <p style={styles.mutedSmall}>
          В самом приложении Google Календаря подписки по ссылке нет — её заводят только в веб-версии. И обновляет
          такие календари Google по своему расписанию: от нескольких часов до суток. Если нужно быстрее, поставьте
          бесплатное приложение <b>ICSx⁵</b>, вставьте туда ту же ссылку и задайте период обновления — с ним работает и
          кнопка «Подписаться».
        </p>
      </>
    );
  }

  return (
    <>
      <ol style={styles.calendarSteps}>
        <li>
          Нажмите «Подписаться» — календарь компьютера (Apple Календарь, Outlook) предложит добавить подписку.
        </li>
        <li>
          Для Google Календаря: «Скопировать ссылку», затем на <b>calendar.google.com</b> слева «Другие календари» →
          «+» → «Подписаться на календарь» → вставьте ссылку.
        </li>
      </ol>
      <p style={styles.mutedSmall}>
        Подписка привязана к аккаунту календаря, а не к устройству: добавили в Google или iCloud — календарь появится
        и на телефоне.
      </p>
    </>
  );
}

// Состояние подписки: когда файл обновился и не было ли ошибки, — и что
// проверить, если в телефоне остались старые даты. Раньше автообновление
// молчало: не получилось — и в календаре навсегда оставалась первая версия.
export function CalendarSyncNote({ sync, platform, styles }) {
  const time = sync.at ? sync.at.toLocaleTimeString("ru-RU", { hour: "2-digit", minute: "2-digit" }) : "";
  return (
    <div style={styles.calendarSync} data-calendar-sync>
      {sync.error ? (
        <p style={styles.calendarSyncError}>
          Файл подписки не обновился: {sync.error}. Попробую ещё раз через минуту — или нажмите «Обновить».
        </p>
      ) : sync.at ? (
        <p style={styles.calendarSyncOk}>
          Файл подписки обновлён в {time} · событий в нём: {sync.count}.
        </p>
      ) : (
        <p style={styles.mutedSmall}>Файл подписки обновляется сам через несколько секунд после любой правки.</p>
      )}
      <details style={styles.calendarTrouble}>
        <summary style={styles.calendarTroubleHead}>В календаре старые даты?</summary>
        <ul style={styles.calendarSteps}>
          <li>
            События, добавленные <b>файлом</b> («Добавить все», импорт .ics), не обновляются никогда — это копия.
            Удалите их и подпишитесь по ссылке: подписанный календарь называется «Ежедневник лицеиста» и стоит
            отдельно от остальных.
          </li>
          {platform === "android" ? (
            <li>
              Google Календарь перечитывает подписки сам, раз в несколько часов, иногда реже, и ускорить это нельзя. С
              приложением <b>ICSx⁵</b> можно задать период обновления хоть раз в 15 минут.
            </li>
          ) : platform === "ios" ? (
            <li>
              iPhone перечитывает подписку по своему расписанию: Настройки → Календарь → Учётные записи → «Загрузка
              данных» — поставьте «Ежечасно» или «Каждые 15 минут».
            </li>
          ) : (
            <li>
              Календарь перечитывает подписку сам: Apple — по своей настройке (обычно раз в час), Google — раз в
              несколько часов, иногда реже.
            </li>
          )}
        </ul>
      </details>
    </div>
  );
}
