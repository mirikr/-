import React from "react";

// Путь к подписке у каждой системы свой, и различия не косметические:
// iPhone подписывается по ссылке одним касанием, Android из приложения
// Google Календаря — не умеет вовсе, там подписка заводится в веб-версии.
// Поэтому инструкция одна, но текст разный.
export default function CalendarHowTo({ platform, styles }) {
  if (platform === "ios") {
    return (
      <ol style={styles.calendarSteps}>
        <li>Нажмите «Подписаться» — iPhone спросит, в какой аккаунт добавить календарь.</li>
        <li>
          Готово: календарь «Ежедневник лицеиста» встанет рядом с остальными и будет обновляться сам, примерно раз в
          час.
        </li>
      </ol>
    );
  }

  if (platform === "android") {
    return (
      <>
        <ol style={styles.calendarSteps}>
          <li>Нажмите «Скопировать ссылку».</li>
          <li>
            Откройте <b>calendar.google.com</b> — с компьютера или в браузере телефона.
          </li>
          <li>Слева «Другие календари» → «+» → «Подписаться на календарь» → вставьте ссылку.</li>
          <li>Календарь появится и в приложении Google Календаря на телефоне.</li>
        </ol>
        <p style={styles.mutedSmall}>
          В самом приложении Google Календаря подписки по ссылке нет — её заводят только в веб-версии. И обновляет
          такие календари Google по своему расписанию: от нескольких часов до суток. Если нужно быстрее, поставьте
          бесплатное приложение <b>ICSx⁵</b>, вставьте туда ту же ссылку и задайте период обновления — с ним работает и
          кнопка «Подписаться».
        </p>
      </>
    );
  }

  return (
    <>
      <ol style={styles.calendarSteps}>
        <li>
          Нажмите «Подписаться» — календарь компьютера (Apple Календарь, Outlook) предложит добавить подписку.
        </li>
        <li>
          Для Google Календаря: «Скопировать ссылку», затем на <b>calendar.google.com</b> слева «Другие календари» →
          «+» → «Подписаться на календарь» → вставьте ссылку.
        </li>
      </ol>
      <p style={styles.mutedSmall}>
        Подписка привязана к аккаунту календаря, а не к устройству: добавили в Google или iCloud — календарь появится
        и на телефоне.
      </p>
    </>
  );
}
