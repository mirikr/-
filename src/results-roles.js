// Кто может выкладывать результаты ученикам (роль «учитель»).
//
// Роль выдаётся по почте: почта добавляется сюда и выходит с обновлением.
// Подделать её нельзя: почту автора каждой выложенной строки записывает сама
// база (supabase/results.sql), а ученик видит только строки, чей автор есть в
// этом списке. Почты — строчными.
export const TEACHERS = [];

export function isTeacher(email) {
  const e = String(email || "").trim().toLowerCase();
  return !!e && TEACHERS.includes(e);
}
