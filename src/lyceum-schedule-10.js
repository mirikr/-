// Одна строка — один вариант урока в конкретной клетке сетки.
//   d — день, n — номер урока, s — предмет, t — преподаватель, r — кабинет.
//   Кому урок: sch — список академических школ, v/o — группа и её вариант,
//   spec — спецкурс (ходят по записи; список — если пара общая для двух
//   спецкурсов, как финансовая грамотность у экономистов и обществоведов),
//   ничего — вся параллель.
//   lvl — если роль урока не выводится из того, кому он адресован: профильный
//   английский идёт у тех же групп, что и базовый, но четыре раза в неделю.
