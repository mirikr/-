// Уровень может быть не для всех школ: профильной математики у юристов нет.
export function tiersForSchool(variant, school) {
  return (variant.tiers || []).filter((t) => !t.schools || t.schools.includes(school));
}

// Алгебру и геометрию спрашивать незачем, пока не выбрана профильная математика.
export function variantVisible(variant, tiers) {
  const need = variant.requires;
  return !need || (tiers || {})[need.variant] === need.tier;
}

export function tierOfOption(variant, optionId) {
  if (!variant.tiers) return null;
  const tier = variant.tiers.find((t) => t.options.some((o) => o.id === optionId));
  return tier ? tier.id : null;
}

// Спрашивать про алгебру у школы права незачем — вопросов и так много.
export function variantsForSchool(school) {
  return VARIANTS.filter((v) => !v.schools || v.schools.includes(school));
}

function levelOf(slot) {
  if (slot.who.spec) return /онлайн|ЮФУ/.test(slot.room) ? "outside" : "olymp";
  if (slot.lvl) return slot.lvl;
  if (slot.who.sch) return "prof";
  return "base";
}

// Одна клетка сетки — один урок. Кто «своее», тот и остаётся: урок своей школы
// перебивает общий («Алгебра» вместо «Математики»), а спецкурс — всё остальное,
// потому что на него записываются отдельно и ходят вместо седьмого урока.
function rankOf(slot) {
  if (slot.who.spec) return 4;
  if (slot.who.sch) return 3;
  if (slot.who.v) return 2;
  return 1;
}

function fits(slot, school, groups, specs) {
  const w = slot.who;
  if (w.spec) return [].concat(w.spec).some((id) => specs.includes(id));
  if (w.sch && !w.sch.includes(school)) return false;
  if (w.v && groups[w.v] !== w.o) return false;
  return true;
}

export const PRESET_ID = "lyceum10";

// Собирает личное расписание: школа, группы и спецкурсы на входе — готовые
// записи расписания на выходе.
export function buildSchedule(choices) {
  const school = (choices && choices.school) || "";
  const groups = (choices && choices.groups) || {};
  const specs = (choices && choices.specs) || [];

  const best = new Map(); // "день#урок" → выигравшие варианты
  for (const slot of SLOTS) {
    if (!fits(slot, school, groups, specs)) continue;
    const key = slot.day + "#" + slot.n;
    const rank = rankOf(slot);
    const cur = best.get(key);
    if (!cur || rank > cur.rank) best.set(key, { rank, slots: [slot] });
    else if (rank === cur.rank) cur.slots.push(slot);
  }

  const out = [];
  for (const slot of SLOTS) {
    const cell = best.get(slot.day + "#" + slot.n);
    if (!cell || !cell.slots.includes(slot)) continue;
    const bell = BELLS[slot.n] || ["08:30", "09:10"];
    const level = levelOf(slot);
    out.push({
      id: "sch-" + PRESET_ID + "-" + slot.day + "-" + slot.n + "-" + out.length,
      day: slot.day,
      kind: "lesson",
      subjectName: slot.subject,
      level,
      priority: level === "base" ? 1 : 2,
      start: bell[0],
      end: bell[1],
      room: slot.room,
      teacher: slot.teacher,
      place: "",
      url: "",
      date: "",
      preset: PRESET_ID,
    });
  }
  return out.sort((a, b) => a.start.localeCompare(b.start));
}
